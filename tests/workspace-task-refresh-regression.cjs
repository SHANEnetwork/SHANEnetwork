const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'workspace.html'), 'utf8');
const start = source.indexOf('async function loadTasks()');
const end = source.indexOf('$("refreshTasks").onclick=loadTasks;', start);
assert(start >= 0 && end > start, 'Shared task loader must exist');
const loader = source.slice(start, end);
assert(source.includes('let taskLoadGeneration=0;'), 'Task refresh generation initialized');
assert(loader.includes('const generation=++taskLoadGeneration;'), 'Each task refresh advances generation');
assert(loader.includes('if(generation!==taskLoadGeneration||!host.isConnected)return;'), 'Stale or detached task views ignored');
assert(loader.indexOf('if(generation!==taskLoadGeneration||!host.isConnected)return;') < loader.indexOf('host.replaceChildren();'), 'Stale response guard precedes task list replacement');
assert(loader.includes('.order("created_at",{ascending:false}).order("id",{ascending:false}).range(page*100,page*100+99)'), 'Tasks are fetched newest first in bounded pages');
assert(loader.includes('older.onclick=()=>loadTasks(page+1)'), 'Older task navigation works');
assert(loader.includes('newer.onclick=()=>loadTasks(page-1)'), 'Newer task navigation works');
assert(source.includes('$("refreshTasks").onclick=()=>loadTasks()'), 'Refresh returns to newest tasks');
assert(loader.includes('if(!error)await Promise.all([loadTasks(page),loadActivity()])'), 'Task mutations preserve current page');
assert(loader.includes('No tasks remain on this page. Return to newer tasks.'), 'Empty older pages explain recovery');
assert(source.includes('function openTaskEditor(task,row,page)'), 'Editor receives current task page');
assert(source.includes('edit.onclick=()=>openTaskEditor(x,row,page)'), 'Edit button passes current page');
assert(source.includes('else await Promise.all([loadTasks(page),loadActivity()])}};row.append(form)'), 'Task save preserves current page');
