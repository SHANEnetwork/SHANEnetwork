// Regression contract for endeavor save idempotency. Run with Node.
// Source assertions only; two-account and browser verification remain required.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','builder.html'),'utf8');
const begin=html.indexOf('let endeavorAccountSaveInFlight=false;');
const end=html.indexOf('document.getElementById("loadEndeavorAccount")',begin);
assert(begin>=0&&end>begin,'save handler exists');
const handler=html.slice(begin,end);
const lock=handler.indexOf('endeavorAccountSaveInFlight=true');
const auth=handler.indexOf('await sb.auth.getUser()');
assert(lock>=0&&auth>lock,'save locks before async auth');
assert(handler.includes('if(endeavorAccountSaveInFlight)return'),'duplicate invocation exits');
assert(handler.includes('endeavorAccountSaveInFlight=false;\n  saveButton.disabled=false;'),'finally releases lock');
assert(handler.includes('.insert(payload).select("id").single()'),'new endeavor saves through account');
assert(handler.includes('shane:endeavor-account-saved'),'successful save emits continuity event');
assert(html.includes('newEndeavor").onclick=()=>{if(endeavorAccountSaveInFlight)'), 'new endeavor action waits for active save');
assert(html.includes('openEndeavor").onclick=async()=>{const out=document.getElementById("planRecoveryStatus"),id=document.getElementById("savedEndeavors").value;if(endeavorAccountSaveInFlight)'), 'opening another endeavor waits for active save');
assert(handler.includes('const endeavorAtSaveStart=activeEndeavorId;'), 'save captures original endeavor identity');
assert(handler.includes('.eq("id",endeavorAtSaveStart)'), 'update targets captured identity');
const latest=html.slice(html.indexOf('document.getElementById("loadEndeavorAccount").onclick='),html.indexOf('async function refreshEndeavors()'));
assert(latest.includes('if(endeavorAccountSaveInFlight)'), 'latest endeavor load checks in-flight save');
assert(latest.includes('An endeavor save started while loading.'), 'latest endeavor load rechecks after database response');
const open=html.slice(html.indexOf('document.getElementById("openEndeavor").onclick='),html.indexOf('document.getElementById("linkEndeavorSite").onclick='));
assert(open.includes('An endeavor save started while loading.'), 'selected endeavor load rechecks after database response');
assert(html.includes('let activeEndeavorId=null;let endeavorLoadEpoch=0;'), 'load epoch initialized');
assert(html.includes('endeavorLoadEpoch++;activeEndeavorId=null;'), 'new endeavor invalidates pending loads');
assert(handler.includes('endeavorLoadEpoch++;saveButton.disabled=true;'), 'save invalidates pending loads');
assert(latest.includes('const loadEpoch=++endeavorLoadEpoch;'), 'latest account load has request epoch');
assert((latest.match(/loadEpoch!==endeavorLoadEpoch/g)||[]).length>=2, 'latest load discards stale results');
assert(open.includes('const loadEpoch=++endeavorLoadEpoch;'), 'selected endeavor load has request epoch');
assert((open.match(/loadEpoch!==endeavorLoadEpoch/g)||[]).length>=2, 'selected load discards stale results');
const refresh=html.slice(html.indexOf('async function refreshEndeavors()'),html.indexOf('document.getElementById("refreshEndeavors").onclick='));
assert(!refresh.includes('window.shaneDirectEndeavorOpened=true'), 'direct return is not marked complete before opening');
assert(open.includes('if(new URLSearchParams(location.search).get("endeavor")===id)window.shaneDirectEndeavorOpened=true;'), 'direct return completes after successful opening');
console.log('Endeavor save source-contract assertions passed; runtime tests still required.');
